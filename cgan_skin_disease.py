"""## 11. Generate images for a specific class"""

def generate_for_class(generator, class_index, num_classes, latent_dim, n=8):
    noise = tf.random.normal(shape=(n, latent_dim))
    labels = np.zeros((n, num_classes), dtype="float32")
    labels[:, class_index] = 1.0
    labels = tf.convert_to_tensor(labels)  # match noise's tensor type
    imgs = generator([noise, labels], training=False)
    imgs = (imgs * 127.5 + 127.5).numpy().astype("uint8")
    return imgs


