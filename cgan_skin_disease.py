"""## 4. Data pipeline"""

def build_datasets():
    """
    Loads images from DATASET_DIR (one sub-folder per class), resizes them,
    one-hot encodes the labels, and rescales pixels to [-1, 1] (to match
    the generator's tanh output).
    """
    raw_ds = keras.utils.image_dataset_from_directory(
        DATASET_DIR,
        label_mode="categorical",
        image_size=(IMG_SIZE, IMG_SIZE),
        batch_size=BATCH_SIZE,
        shuffle=True,
        seed=SEED,
    )

    class_names = raw_ds.class_names
    num_classes = len(class_names)
    print(f"Found {num_classes} classes: {class_names}")

    def preprocess(images, labels):
        images = tf.cast(images, tf.float32)
        images = (images - 127.5) / 127.5  # -> [-1, 1]
        return images, labels

    ds = raw_ds.map(preprocess, num_parallel_calls=tf.data.AUTOTUNE)
    ds = ds.prefetch(tf.data.AUTOTUNE)
    return ds, num_classes, class_names


dataset, NUM_CLASSES, CLASS_NAMES = build_datasets()

"""## 5. Generator"""

def build_generator(latent_dim, num_classes, img_size, channels):
    """
    Input: noise vector (latent_dim,) concatenated with one-hot label (num_classes,)
    Output: (img_size, img_size, channels) image in [-1, 1]
    """
    start_size = img_size // 16  # 4 upsampling stages of stride 2 -> x16
    assert start_size * 16 == img_size, "IMG_SIZE must be divisible by 16 (e.g. 64, 128)"

    noise_input = keras.Input(shape=(latent_dim,), name="noise")
    label_input = keras.Input(shape=(num_classes,), name="label")

    x = layers.Concatenate()([noise_input, label_input])
    x = layers.Dense(start_size * start_size * 256, use_bias=False)(x)
    x = layers.BatchNormalization()(x)
    x = layers.LeakyReLU(0.2)(x)
    x = layers.Reshape((start_size, start_size, 256))(x)

    for filters in [256, 128, 64, 32]:
        x = layers.Conv2DTranspose(
            filters, kernel_size=4, strides=2, padding="same", use_bias=False
        )(x)
        x = layers.BatchNormalization()(x)
        x = layers.LeakyReLU(0.2)(x)

    out = layers.Conv2D(
        channels, kernel_size=5, padding="same", activation="tanh", name="gen_output"
    )(x)

    return keras.Model([noise_input, label_input], out, name="generator")


generator = build_generator(LATENT_DIM, NUM_CLASSES, IMG_SIZE, CHANNELS)
generator.summary()

"""## 6. Discriminator"""

def build_discriminator(num_classes, img_size, channels):
    """
    The label is broadcast into an (img_size, img_size, 1) tensor derived from
    a dense projection of the one-hot vector, and concatenated with the image
    along the channel axis, following the conditioning trick in the Keras
    CGAN example.
    """
    image_input = keras.Input(shape=(img_size, img_size, channels), name="image")
    label_input = keras.Input(shape=(num_classes,), name="label")

    label_channels = layers.Dense(img_size * img_size)(label_input)
    label_channels = layers.Reshape((img_size, img_size, 1))(label_channels)

    x = layers.Concatenate()([image_input, label_channels])

    for filters in [64, 128, 256, 512]:
        x = layers.Conv2D(filters, kernel_size=4, strides=2, padding="same")(x)
        x = layers.LeakyReLU(0.2)(x)
        x = layers.Dropout(0.3)(x)

    x = layers.Flatten()(x)
    out = layers.Dense(1, name="disc_output")(x)  # raw logit (no sigmoid)

    return keras.Model([image_input, label_input], out, name="discriminator")


discriminator = build_discriminator(NUM_CLASSES, IMG_SIZE, CHANNELS)
discriminator.summary()

"""## 7. ConditionalGAN model (custom `train_step`)"""

class ConditionalGAN(keras.Model):
    def __init__(self, discriminator, generator, latent_dim, num_classes):
        super().__init__()
        self.discriminator = discriminator
        self.generator = generator
        self.latent_dim = latent_dim
        self.num_classes = num_classes
        self.gen_loss_tracker = keras.metrics.Mean(name="generator_loss")
        self.disc_loss_tracker = keras.metrics.Mean(name="discriminator_loss")

    @property
    def metrics(self):
        return [self.gen_loss_tracker, self.disc_loss_tracker]

    def compile(self, d_optimizer, g_optimizer, loss_fn):
        super().compile()
        self.d_optimizer = d_optimizer
        self.g_optimizer = g_optimizer
        self.loss_fn = loss_fn

    def train_step(self, data):
        real_images, one_hot_labels = data
        batch_size = tf.shape(real_images)[0]

        # ---- Train the discriminator ----
        random_latent_vectors = tf.random.normal(shape=(batch_size, self.latent_dim))
        generated_images = self.generator(
            [random_latent_vectors, one_hot_labels], training=True
        )

        combined_images = tf.concat([generated_images, real_images], axis=0)
        combined_labels = tf.concat([one_hot_labels, one_hot_labels], axis=0)

        labels = tf.concat(
            [tf.ones((batch_size, 1)), tf.zeros((batch_size, 1))], axis=0
        )
        # one-sided label smoothing for the "real" targets, as in the reference example
        labels += 0.05 * tf.random.uniform(tf.shape(labels))

        with tf.GradientTape() as tape:
            predictions = self.discriminator(
                [combined_images, combined_labels], training=True
            )
            d_loss = self.loss_fn(labels, predictions)
        grads = tape.gradient(d_loss, self.discriminator.trainable_weights)
        self.d_optimizer.apply_gradients(
            zip(grads, self.discriminator.trainable_weights)
        )

        # ---- Train the generator (via the combined model, discriminator frozen) ----
        random_latent_vectors = tf.random.normal(shape=(batch_size, self.latent_dim))
        misleading_labels = tf.zeros((batch_size, 1))  # pretend generated = real

        with tf.GradientTape() as tape:
            fake_images = self.generator(
                [random_latent_vectors, one_hot_labels], training=True
            )
            predictions = self.discriminator(
                [fake_images, one_hot_labels], training=True
            )
            g_loss = self.loss_fn(misleading_labels, predictions)
        grads = tape.gradient(g_loss, self.generator.trainable_weights)
        self.g_optimizer.apply_gradients(zip(grads, self.generator.trainable_weights))

        self.gen_loss_tracker.update_state(g_loss)
        self.disc_loss_tracker.update_state(d_loss)
        return {
            "g_loss": self.gen_loss_tracker.result(),
            "d_loss": self.disc_loss_tracker.result(),
        }

"""## 8. Callback to preview generated samples during training"""

import matplotlib.pyplot as plt

class GANMonitor(keras.callbacks.Callback):
    def __init__(self, num_classes, class_names, latent_dim, output_dir, every=5, samples_per_class=4):
        self.num_classes = num_classes
        self.class_names = class_names
        self.latent_dim = latent_dim
        self.output_dir = output_dir
        self.every = every
        self.samples_per_class = samples_per_class

    def on_epoch_end(self, epoch, logs=None):
        if (epoch + 1) % self.every != 0:
            return

        total = self.num_classes * self.samples_per_class
        noise = tf.random.normal(shape=(total, self.latent_dim))
        # Use tf ops (not np.eye/np.repeat) so labels stay a tf.Tensor, matching
        # noise's type -- Keras 3 rejects mixed tensor/ndarray items in a call() list.
        labels = tf.repeat(tf.eye(self.num_classes, dtype=tf.float32), self.samples_per_class, axis=0)

        generated = self.model.generator([noise, labels], training=False)
        generated = (generated * 127.5 + 127.5).numpy().astype("uint8")

        grid = self._make_grid(generated, self.num_classes, self.samples_per_class)
        path = os.path.join(self.output_dir, f"epoch_{epoch + 1:04d}.png")
        keras.utils.save_img(path, grid)

        plt.figure(figsize=(self.samples_per_class * 1.5, self.num_classes * 1.5))
        plt.imshow(grid)
        plt.axis("off")
        plt.title(f"Epoch {epoch + 1}")
        plt.show()

        # Save weights of the generator/discriminator directly. These are functional
        # models (built via keras.Input), so they're already "built" -- unlike the
        # ConditionalGAN wrapper, which is never called directly and therefore never
        # gets marked as built. Saving the wrapper's weights (e.g. via ModelCheckpoint)
        # raises "You are saving a model that has not yet been built."
        self.model.generator.save_weights(
            os.path.join(self.output_dir, "checkpoints", f"generator_epoch_{epoch + 1:04d}.weights.h5")
        )

    @staticmethod
    def _make_grid(images, rows, cols):
        h, w, c = images.shape[1:]
        grid = np.zeros((rows * h, cols * w, c), dtype=images.dtype)
        for idx, img in enumerate(images):
            r, col = divmod(idx, cols)
            grid[r * h:(r + 1) * h, col * w:(col + 1) * w, :] = img
        return grid


monitor = GANMonitor(
    num_classes=NUM_CLASSES,
    class_names=CLASS_NAMES,
    latent_dim=LATENT_DIM,
    output_dir=OUTPUT_DIR,
    every=SAMPLE_EVERY,
)

"""## 9. Compile & train"""

cgan = ConditionalGAN(
    discriminator=discriminator,
    generator=generator,
    latent_dim=LATENT_DIM,
    num_classes=NUM_CLASSES,
)

cgan.compile(
    d_optimizer=keras.optimizers.Adam(learning_rate=LEARNING_RATE, beta_1=0.5),
    g_optimizer=keras.optimizers.Adam(learning_rate=LEARNING_RATE, beta_1=0.5),
    loss_fn=keras.losses.BinaryCrossentropy(from_logits=True),
)

# Note: checkpointing is handled inside GANMonitor.on_epoch_end (saves generator
# weights directly), so we only pass `monitor` here -- no separate ModelCheckpoint.
history = cgan.fit(dataset, epochs=EPOCHS, callbacks=[monitor])

